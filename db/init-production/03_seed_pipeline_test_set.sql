    SELECT lost_image_path AS file_path
    FROM pipeline_seed_pair
    WHERE lost_image_path IS NOT NULL
    UNION
    SELECT auction_image_path AS file_path
    FROM pipeline_seed_pair
    WHERE auction_image_path IS NOT NULL
