INSERT INTO image_file (file_path)
SELECT seed_image_path.file_path
FROM seed_image_path
WHERE NOT EXISTS (
    SELECT 1
    FROM image_file existing
    WHERE existing.file_path = seed_image_path.file_path
);

INSERT INTO lost_artwork_image_file (lost_artwork_id, image_file_id)
SELECT
    seed.lost_artwork_id,
    image.image_file_id
FROM pipeline_seed_pair seed
JOIN LATERAL (
    SELECT image_file_id
    FROM image_file
    WHERE file_path = seed.lost_image_path
    ORDER BY image_file_id
    LIMIT 1
) image ON true
WHERE seed.lost_image_path IS NOT NULL
ON CONFLICT (lost_artwork_id, image_file_id) DO NOTHING;

