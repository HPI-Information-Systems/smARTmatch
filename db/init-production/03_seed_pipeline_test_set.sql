-- Seed production with a compact, known-good image- and metadata-matching dataset.
--
-- The first ten pairs keep the pipeline_test_set image links used by the image
-- matching startup checks. All twelve pairs carry catalogue-style descriptions
-- adapted from the project pipeline integrity dataset.
-- Lost artwork rows keep the extracted metadata fields. Auction artwork rows
-- keep the raw catalogue description and auction/file metadata only, leaving
-- extracted fields empty for the metadata-extraction pipeline.
-- The final two pairs are metadata-only seed examples and intentionally do not
-- create image_file links.

